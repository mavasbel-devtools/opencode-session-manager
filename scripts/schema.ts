#!/usr/bin/env bun
/**
 * Store schemas, from the real stores.
 *
 *   bun scripts/schema.ts fixture <store.db> <out.sql>
 *     Writes every CREATE statement of a store (tables, virtual tables, indexes, triggers; not
 *     SQLite's own tables nor the shadow tables a virtual table creates for itself), read with
 *     `select sql from sqlite_master`. The store is opened read-only.
 *
 *   bun scripts/schema.ts generate <fixture.sql> <out.ts> <title>
 *     Writes the Drizzle tables of a fixture: every ordinary table, every column under its own
 *     name, typed by SQLite's affinity rules (integers as BigInt, so no value loses precision).
 *     `tests/unit/sessions/schema.test.ts` regenerates them and fails when they drift.
 */
import { Database } from "bun:sqlite"
import { readFileSync, writeFileSync } from "node:fs"

interface Column {
  readonly name: string
  readonly type: string
}

/** Every CREATE statement a store holds, virtual tables' shadow tables and SQLite's own excluded. */
export function fixtureOf(store: string): string {
  const db = new Database(store, { readonly: true })
  try {
    const rows = db.query("select type, name, sql from sqlite_master where sql is not null order by case type when 'table' then 0 when 'index' then 1 else 2 end, name").all() as {
      type: string
      name: string
      sql: string
    }[]
    const virtual = rows.filter((row) => row.type === "table" && /^create virtual table/i.test(row.sql)).map((row) => row.name)
    const kept = rows.filter((row) => !row.name.startsWith("sqlite_") && !virtual.some((name) => row.name.startsWith(`${name}_`)))
    return kept.map((row) => `${row.sql.trim()};\n`).join("\n")
  } finally {
    db.close()
  }
}

/** The ordinary tables a fixture creates, with their columns, in name order. */
export function tablesOf(fixture: string): { readonly name: string; readonly columns: readonly Column[] }[] {
  const db = new Database(":memory:")
  try {
    db.exec(fixture)
    const names = (db.query("select name, sql from sqlite_master where type = 'table' and name not like 'sqlite_%' order by name").all() as { name: string; sql: string }[])
      .filter((row) => !/^create virtual table/i.test(row.sql))
      .map((row) => row.name)
    const virtual = (db.query("select name from sqlite_master where type = 'table' and sql like 'CREATE VIRTUAL TABLE%'").all() as { name: string }[]).map((row) => row.name)
    return names
      .filter((name) => !virtual.some((table) => name.startsWith(`${table}_`)))
      .map((name) => ({ name, columns: (db.query(`pragma table_info("${name}")`).all() as Column[]).map(({ name, type }) => ({ name, type })) }))
  } finally {
    db.close()
  }
}

/** SQLite's type affinity of a declared column type (https://sqlite.org/datatype3.html, 3.1). */
function builderOf(declared: string): string {
  const type = declared.toUpperCase()
  if (type.includes("INT")) return "bigInteger"
  if (type.includes("CHAR") || type.includes("CLOB") || type.includes("TEXT")) return "text"
  if (type === "" || type.includes("BLOB")) return "value"
  if (type.includes("REAL") || type.includes("FLOA") || type.includes("DOUB")) return "real"
  return "value"
}

function identifier(name: string): string {
  return name.replace(/_([a-z0-9])/g, (_match, letter: string) => letter.toUpperCase())
}

export function generate(fixture: string, title: string): string {
  const tables = tablesOf(fixture)
  const used = new Set(tables.flatMap((table) => table.columns.map((column) => builderOf(column.type))))
  const core = ["real", "text"].filter((builder) => used.has(builder))
  const custom = ["bigInteger", "value"].filter((builder) => used.has(builder))
  const lines = [
    `// Generated by \`bun scripts/schema.ts generate\` from ${title}. Do not edit; regenerate.`,
    `import { sqliteTable${core.map((builder) => `, ${builder}`).join("")} } from "drizzle-orm/sqlite-core"`,
    ...(custom.length > 0 ? [`import { ${custom.join(", ")} } from "@session-manager/infrastructure/adapters/outbound/sqlite/schema/value"`] : []),
    "",
  ]
  for (const table of tables) {
    lines.push(`export const ${identifier(table.name)} = sqliteTable("${table.name}", {`)
    for (const column of table.columns) {
      const builder = builderOf(column.type)
      lines.push(`  ${JSON.stringify(column.name)}: ${builder}(${JSON.stringify(column.name)}),`)
    }
    lines.push("})", "")
  }
  lines.push("/** Every table, by its name in the store. */", "export const TABLES = {")
  for (const table of tables) lines.push(`  ${JSON.stringify(table.name)}: ${identifier(table.name)},`)
  lines.push("} as const", "")
  return lines.join("\n")
}

if (import.meta.main) {
  const [command, input, output, title] = process.argv.slice(2)
  if (command === "fixture" && input !== undefined && output !== undefined) writeFileSync(output, fixtureOf(input))
  else if (command === "generate" && input !== undefined && output !== undefined && title !== undefined) writeFileSync(output, generate(readFileSync(input, "utf8"), title))
  else {
    process.stderr.write("usage: bun scripts/schema.ts fixture <store.db> <out.sql> | generate <fixture.sql> <out.ts> <title>\n")
    process.exit(2)
  }
}
